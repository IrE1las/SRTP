def clean(q):
    if q['id'] in MANUAL:
        return MANUAL[q['id']]
    s = q['stem']
    s = s.replace('在6502车站信号课件所述范围内，', '6502电气集中电路中，')
    s = s.replace('在6502车站信号课件所述正常解锁电路举例中，', '6502正常解锁电路中，')
    s = s.replace('在6502车站信号课件所述停电恢复处理中，', '6502电气集中设备停电恢复时，')
    s = s.replace('在6502车站信号课件所举从左向右进路中，', '6502电气集中电路中，办理从左向右的进路时，')
    s = s.replace('在课件所述6502电路中，', '6502电气集中电路中，')
    s = s.replace('按课件所述6502人工延时解锁过程，', '6502人工延时解锁时，')
    s = s.replace('在课件所述6502人工延时解锁中，', '6502人工延时解锁时，')
    s = s.replace('课件所述6502人工延时解锁中，', '6502人工延时解锁时，')
    s = s.replace('课件所述6502电路中，', '6502电气集中电路中，')
    s = s.replace('课件所述6502取消进路的检查条件中，', '6502电气集中办理取消进路时，')
    s = s.replace('课件中的6502人工解锁延时电路，', '6502人工解锁延时电路中，')
    s = re.sub(r'^(依据|根据)《[^》]+》(?:（[^）]*）)?[，,]\s*', '', s)
    for before, after in INNER.items():
        s = s.replace(before, after)
    return s.strip()


def signature(q):
    return hashlib.sha256(json.dumps({k: q.get(k) for k in ('id','chapter','kind','stem','options','answer','answer_status')}, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


